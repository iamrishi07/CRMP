CREATE TABLE DIVISIONS (
    DIVISION_ID         NUMBER(10)      NOT NULL,
    DIVISION_NAME       VARCHAR2(200)   NOT NULL,
    DIVISION_CODE       VARCHAR2(20)    NOT NULL,
    PARENT_DIVISION_ID  NUMBER(10),
    IS_ACTIVE           NUMBER(1)       DEFAULT 1 NOT NULL,
    CREATED_AT          TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_DIVISIONS PRIMARY KEY (DIVISION_ID),
    CONSTRAINT UQ_DIV_CODE UNIQUE (DIVISION_CODE),
    CONSTRAINT FK_DIV_PARENT FOREIGN KEY (PARENT_DIVISION_ID) REFERENCES DIVISIONS(DIVISION_ID)
);

CREATE TABLE BUILDINGS (
    BUILDING_ID     NUMBER(10)      NOT NULL,
    BUILDING_NAME   VARCHAR2(200)   NOT NULL,
    BUILDING_CODE   VARCHAR2(20)    NOT NULL,
    IS_ACTIVE       NUMBER(1)       DEFAULT 1 NOT NULL,
    CONSTRAINT PK_BUILDINGS PRIMARY KEY (BUILDING_ID),
    CONSTRAINT UQ_BLDG_CODE UNIQUE (BUILDING_CODE)
);

CREATE TABLE ROLES (
    ROLE_ID     NUMBER(10)      NOT NULL,
    ROLE_CODE   VARCHAR2(50)    NOT NULL,
    ROLE_NAME   VARCHAR2(100)   NOT NULL,

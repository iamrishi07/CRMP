CREATE TABLE REQUESTS (
    REQUEST_ID              NUMBER(10)      NOT NULL,
    REQUEST_NUMBER          VARCHAR2(30)    NOT NULL,
    TYPE_ID                 NUMBER(10)      NOT NULL,
    SUBMITTER_USER_ID       NUMBER(10)      NOT NULL,
    ON_BEHALF_OF_USER_ID    NUMBER(10),
    DIVISION_ID             NUMBER(10)      NOT NULL,
    STATUS                  VARCHAR2(30)    DEFAULT 'PENDING_APPROVAL' NOT NULL,
    CURRENT_STAGE_ID        NUMBER(10),
    TECH_EXPERT_ID          NUMBER(10),

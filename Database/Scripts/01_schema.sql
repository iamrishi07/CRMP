    PRIORITY                VARCHAR2(20)    DEFAULT 'NORMAL' NOT NULL,
    SLA_DEADLINE            TIMESTAMP,
    IS_SLA_BREACHED         NUMBER(1)       DEFAULT 0 NOT NULL,
    SLA_BREACH_NOTIFIED     NUMBER(1)       DEFAULT 0 NOT NULL,
    SLA_WARN_NOTIFIED       NUMBER(1)       DEFAULT 0 NOT NULL,
    SUBMITTED_AT            TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    RESOLVED_AT             TIMESTAMP,
    CLOSED_AT               TIMESTAMP,
    RESOLUTION_NOTES        CLOB,
    CREATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT              TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_REQUESTS PRIMARY KEY (REQUEST_ID),
    CONSTRAINT UQ_REQUEST_NUMBER UNIQUE (REQUEST_NUMBER),
    CONSTRAINT FK_REQ_TYPE FOREIGN KEY (TYPE_ID) REFERENCES REQUEST_TYPES(TYPE_ID),
    CONSTRAINT FK_REQ_SUBMITTER FOREIGN KEY (SUBMITTER_USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_REQ_ONBEHALF FOREIGN KEY (ON_BEHALF_OF_USER_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT FK_REQ_DIVISION FOREIGN KEY (DIVISION_ID) REFERENCES DIVISIONS(DIVISION_ID),
    CONSTRAINT FK_REQ_STAGE FOREIGN KEY (CURRENT_STAGE_ID) REFERENCES WORKFLOW_STAGES(STAGE_ID),
    CONSTRAINT FK_REQ_TECH FOREIGN KEY (TECH_EXPERT_ID) REFERENCES USERS(USER_ID),
    CONSTRAINT CK_REQ_STATUS CHECK (STATUS IN ('DRAFT','PENDING_APPROVAL','APPROVED','REJECTED','IN_PROGRESS','RESOLVED','CLOSED','CANCELLED')),
    CONSTRAINT CK_REQ_PRIORITY CHECK (PRIORITY IN ('LOW','NORMAL','HIGH','URGENT'))
);

